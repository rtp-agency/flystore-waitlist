export type IconName = keyof typeof ICONS;

/**
 * Готовая разметка знака.
 *
 * Возвращает строку, а не элемент: половина интерфейса кабинета собирается
 * шаблонными строками, и знаку нужно уметь встать в них так же, как в разметку
 * страницы. Размер задаётся атрибутом, а не классом: файл с иконками может
 * не попасть в обход сборщика, и тогда класс просто не сгенерируется.
 */
export function icon(name: string, size = 18, cls = ""): string {
  const body = ICONS[name];
  if (!body) return "";

  return (
    `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" ` +
    `stroke="currentColor" stroke-width="1.6" stroke-linecap="round" ` +
    `stroke-linejoin="round" aria-hidden="true"${cls ? ` class="${cls}"` : ""}>${body}</svg>`
  );
}
